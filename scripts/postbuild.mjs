// After `astro build`: check the pages, then get dist/ ready for Spacefast.
// 1. SEO checks. Every indexable page: one H1, a title of 60 characters or
//    less, a description of 120 to 160, a canonical address ending in a
//    slash, JSON-LD and a Markdown copy. Any failure stops the build, so a
//    broken page is never published.
// 2. Copy the server functions (spacefast/functions) and sf.jsonc (which
//    gives the waitlist its database) into dist/.
// 3. Spacefast turns uploaded .md files into pages, so each Markdown copy
//    becomes a tiny function that returns it as text/markdown at the same
//    address, and the .md file itself is removed.
import { cpSync, readdirSync, readFileSync, rmSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';

const dist = 'dist';
const walk = (dir, ext) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = join(dir, e.name);
  if (e.isDirectory()) return p === join(dist, 'functions') || p === join(dist, '_astro') ? [] : walk(p, ext);
  return e.name.endsWith(ext) ? [p] : [];
});
const decode = (s) => s.replace(/&amp;/g, '&').replace(/&#39;|&#x27;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');

// 1. SEO checks
const problems = [];
for (const file of walk(dist, '.html')) {
  const html = readFileSync(file, 'utf8');
  const page = '/' + relative(dist, file).replace(/index\.html$/, '').replace(/\\/g, '/');
  if (/<meta name="robots" content="noindex"/.test(html)) continue;
  const title = decode((html.match(/<title>([^<]*)<\/title>/) || [])[1] || '');
  const desc = decode((html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '');
  const h1 = (html.match(/<h1[\s>]/g) || []).length;
  const canonical = (html.match(/<link rel="canonical" href="([^"]*)"/) || [])[1] || '';
  const md = (html.match(/<link rel="alternate" type="text\/markdown" href="https:\/\/bridle\.to([^"]*)"/) || [])[1] || '';
  if (h1 !== 1) problems.push(`${page}: ${h1} H1s`);
  if (!title || title.length > 60) problems.push(`${page}: title is ${title.length} characters`);
  if (desc.length < 120 || desc.length > 160) problems.push(`${page}: description is ${desc.length} characters`);
  if (!canonical.endsWith('/')) problems.push(`${page}: canonical "${canonical}"`);
  if (!html.includes('application/ld+json')) problems.push(`${page}: no JSON-LD`);
  if (!md || !existsSync(join(dist, md))) problems.push(`${page}: no Markdown copy at ${md}`);
  if (/ — | – /.test(html.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/g, ''))) problems.push(`${page}: a dash used as punctuation`);
}
if (problems.length) {
  console.error('SEO check failed:\n- ' + problems.join('\n- '));
  process.exit(1);
}
console.log('SEO check passed');

// 2. Functions and the runtime config. The price functions get the steps
//    from src/data/deal.json and the launch switch from src/data/site.ts
//    (CHECKOUT_OPEN), so the page and the checkout never disagree.
mkdirSync(join(dist, 'functions'), { recursive: true });
cpSync('spacefast/functions', join(dist, 'functions'), { recursive: true });
cpSync('sf.jsonc', join(dist, 'sf.jsonc'));
const dealJson = JSON.stringify(JSON.parse(readFileSync('src/data/deal.json', 'utf8')));
const checkoutOpen = /export const CHECKOUT_OPEN = true;/.test(readFileSync('src/data/site.ts', 'utf8'));
for (const f of readdirSync(join(dist, 'functions', 'api'))) {
  const p = join(dist, 'functions', 'api', f);
  const src = readFileSync(p, 'utf8');
  if (src.includes('/*DEAL_JSON*/') || src.includes('/*CHECKOUT_OPEN*/')) {
    writeFileSync(p, src.replace('/*DEAL_JSON*/ null', dealJson).replace('/*CHECKOUT_OPEN*/ false', String(checkoutOpen)));
  }
}

// 3. Markdown copies as functions
for (const path of walk(dist, '.md')) {
  const rel = relative(dist, path);
  const text = readFileSync(path, 'utf8');
  const fn = `// Generated by scripts/postbuild.mjs from ${rel}. Do not edit.
const TEXT = ${JSON.stringify(text)};
export function GET() {
  return new Response(TEXT, { headers: { 'Content-Type': 'text/markdown; charset=utf-8', 'Cache-Control': 'public, max-age=300' } });
}
`;
  const out = join(dist, 'functions', `${rel}.ts`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, fn);
  rmSync(path);
  console.log(`markdown copy: /${rel} -> functions/${rel}.ts`);
}
